## ── 与 EquipSystem 常量同口径(单位: 占 R_OUT 的比例) ──
R_IN = 500.0 / 800.0          # 0.625   判定带内半径
R_MID = 650.0 / 800.0         # 0.8125  判定带中心 = 斩痕走的那条线
R_OUT = 1.0                   #         判定带外半径
HALF_DEG = 30.0               # BLADE_ARC_DEG / 2
VIEW = 0.525                  # 画布半宽(占 R_OUT 的比例)
SS = 6                        # 超采样倍数

## steel 板(与 tools/pixelize_sheet.py 的 PALETTES["steel"] 一致, 索引 0 最亮)
P = [
    (246, 248, 252),   # 0 刃芯高光
    (206, 216, 232),   # 1 亮钢
    (168, 182, 204),   # 2 主钢
    (118, 132, 158),   # 3 暗钢
    ( 74,  86, 110),   # 4 阴影
    ( 38,  46,  64),   # 5 近黑
]


## Bayer 4x4 有序抖动矩阵(阈值 0..15)。★用它而不是哈希噪点:
## 哈希读成噪点/磨砂, 有序抖动读成网点/半调 —— 后者是像素画里表达"半透明"的标准手法。
BAYER4 = [
    [0, 8, 2, 10],
    [12, 4, 14, 6],
    [3, 11, 1, 9],
    [15, 7, 13, 5],
]


def _frac(x):
    """确定性伪随机 0..1 —— 同一个 x 永远给同一个值(可复现, 不用 random)。"""
    v = math.sin(x * 12.9898) * 43758.5453
    return v - math.floor(v)


def _wobble(a, seed, amp, freq):
    """沿角度 a 的低频抖动: 让弧不是数学上完美的圆弧(完美 = 读成程序生成)。"""
    return amp * (math.sin(a * freq + seed) * 0.6 + math.sin(a * freq * 2.7 + seed * 1.7) * 0.4)


## ─────────────────────────────────────────────────────────────
## 预警区 band —— 一片**填充**的环形扇区, 不是几条线
## ─────────────────────────────────────────────────────────────
def _shade_band(r, a, half, t, pxq):
    """pxq = (最终像素 x, 最终像素 y), 抖动只能用它。

    ★★这一版是照着【和旧版并排量】改的(2026-09-09):
      第一版我拿"底色 + 矩形短划"填满整条带, 上屏读成**铺了砖的板**。
      并排量才看清差别在哪 ——
        旧版(用户认可的那版): 区域内 **148 种颜色的平滑渐变**, 中位亮度 89 ⇒ 读作**地上的一片光**
        我第一版:            **4 档硬边、70% 是同一个平色** + 矩形短划 ⇒ 读作**板**
      (顺带纠正我自己的目测: 我以为新版"太亮太实", 实测中位亮度 58 < 旧版 89, 是**更暗**的。)
    ★像素画不能用平滑渐变, 但有等价手段: **Bayer 有序抖动**做的渐变。
      覆盖率从带心往两端递减, 稀的地方**直接透出地面** —— 这才是"光", 不是"漆"。
      用 Bayer 而不是哈希噪点: 哈希读成**噪点/磨砂**, 有序抖动读成**网点/半调**, 是印刷与像素画里
      表达"半透明"的标准手法。
    ★仍然保留三样**信息量**(预兆必须自带信息, 不能只是好看):
      · 内外两条边界弧(实心) = 判定带的两个边在哪
      · 带心一条更亮的线(实心) = 斩痕待会儿落在哪
      · 角向两端**不封口**(靠覆盖率归零自然消散) —— 闭合的亮轮廓永远读作物体
    """
    qx, qy = pxq
    ua = abs(a) / half
    th = float(BAYER4[qy & 3][qx & 3]) / 16.0
    ## ★两端一起化开: 最后 15% 的角度里, 连边界弧与带心线也改成抖动收尾。
    ##   否则填充化开了、两条弧却还是被**直切一刀**, 端头依旧读成"被剪断的板"。
    tip = 1.0 if ua < 0.85 else (1.0 - ua) / 0.15
    ## ① 内外边界: 各一条亮弧, 只画在带内侧(不越界 ⇒ 画出来的范围 == 打得到的范围)
    if r - R_IN < 0.011 or R_OUT - r < 0.011:
        return P[3] if tip > th else None
    ## ② 带心暗示: 斩痕将要走的那条线 —— 全图最亮, 这是预兆的信息量所在
    if abs(r - (R_MID + _wobble(a, 1.7, 0.005, 5.0))) < 0.016:
        return P[2] if tip > th else None
    ## ③ 抖动渐变填充。覆盖率 cov:
    ##    角向 —— 从带心 1.0 递减到两端 0(所以两端是"化开"的, 不是被直切一刀)
    ##    径向 —— 中间略高、贴近两条边界略低(边界由 ① 负责说清, 这里不跟它抢)
    ur = (r - R_MID) / (0.5 * (R_OUT - R_IN))
    cov = (1.0 - ua ** 2.6) * (1.0 - 0.30 * ur * ur)
    cov = max(0.0, cov) * 1.35                      # 1.35: 让带心附近能到第二档
    if cov > 1.0 + th:
        return P[3]
    if cov > th:
        return P[4]
    return None


## ─────────────────────────────────────────────────────────────
## 斩痕 slash —— 沿带心的一条波形亮带, 叠在 band 上面
## ─────────────────────────────────────────────────────────────
def _shade_slash(r, a, half, t, pxq):
    """五帧: 细亮线 → 张开 → 满(热核+冷边) → 碎 → 残片。

    ★消散**只靠碎开**, 颜色全程满亮 —— 旧版实拍 #44-46 / #84-86 是把颜色压暗成灰,
      黑场上读成"飘着几块灰板"。真正的淡出交给代码侧 modulate.a。
    ★热核 + 冷边: 中心 P[0](246,248,252) 往两侧退到 P[1]/P[2] ⇒ 有温度层次,
      不是一整块纯白(旧版这点是对的, 保留)。
    ★波形沿角度走, 不是完美圆弧 —— 旧版那条白光就是波浪形的, 这是它像"劈开"而不像"画了个圈"的原因。
    """
    qx, qy = pxq
    ## 波形中心线: 带心 + 两段不同频率的低频抖动
    ## ★振幅要够: 第一版 ±34 码, 在 300 码宽的带上几乎看不出弯 ⇒ 读成一条光滑白果冻。
    ##   旧版实拍(#24-26)那条白光的起伏约等于它自身的宽度, 这才是它像"劈开"而不像"画了条线"的原因。
    ##   ±78 码, 且 cen±halfw 仍落在 [0.641, 0.985] 判定带内(算过, 不越界)。
    cen = R_MID + _wobble(a, 2.3, 0.075, 2.6) + _wobble(a, 7.9, 0.022, 6.1)
    ## 厚度: 峰值半宽 0.075(=60 码), 约占判定带宽度的三分之一。
    ## ★分母要对得上帧数: 第一版 `0.20 + t/0.30` 在 t=0.25(第 2 帧)就已经是 1.03 ⇒ **f1 与 f2 逐像素完全相同**
    ##   (实测两帧都是 3412 像素), 5 帧只演了 4 帧。改成到 f2 才满。
    grow = min(1.0, 0.30 + t / 0.42)
    halfw = 0.075 * grow
    ## 两端收细(不封口, 也不被直切一刀)
    ## ★两端要**收成尖**: 第一版端点仍留 35% 厚度 ⇒ 钝头, 像被直切一刀。
    tp = 1.0 - (abs(a) / half) ** 1.8
    if tp <= 0.0:
        return None
    halfw *= (0.08 + 0.92 * tp)
    d = abs(r - cen)
    if d > halfw:
        return None
    u = 1.0 - d / halfw                                # 1 = 正中(热核), 0 = 边缘
    ## 碎开: 后 45% 按【角度 × 径向】二维格子开洞, 洞随时间变多变大。
    ## ★只按角度开洞会碎成横向条纹, 读成百叶窗不是碎裂 —— 规律的切分永远读成"图案"。
    if t > 0.55:
        k = (t - 0.55) / 0.45
        ca = math.floor(a * 21.0 + _frac(math.floor(u * 3.0) * 5.3) * 2.0)
        cu = math.floor(u * 3.0)
        if _frac(ca * 1.0 + cu * 7.31) < k * 0.88:
            return None
        if _frac(ca * 2.7 + cu * 3.19) < k * 0.30:
            return None
    ## 温度层次: 热核 → 冷边。边界加低频抖动, 否则等距色带读成等高线。
    ## ★热核必须**细**: 第一版 `u > 0.62` 让最亮色占了 39.5%, 上屏糊成一坨白, 温度层次白做了。
    ##   收到 0.78 后热核约 22%, 剩下的宽度留给 P[1]/P[2] 才读得出"中间烫、两边冷"。
    j = _wobble(a, 4.4, 0.06, 6.0)
    if u > 0.78 + j * 0.5:
        return P[0]
    if u > 0.46 + j:
        return P[1]
    if u > 0.18 + j:
        return P[2]
    ## 最外一圈用点画收边 ⇒ 硬边但不生硬, 且缩小后不会糊成一条灰线
    if _frac(qx * 5.1 + qy * 2.9) < 0.55:
        return P[3]
    return None


def render_cell(mode, d_ang, f, nframes, px):
    """渲一格(某方向某帧)的大图, 返回 RGBA Image。"""
    n = px * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    ld = img.load()
    half = math.radians(HALF_DEG)
    t = f / float(max(1, nframes - 1))          # 0..1 帧进度
    ox = R_MID * math.cos(d_ang)                # 画布中心 = 释放点 + 瞄准方向 × 带心半径
    oy = R_MID * math.sin(d_ang)
    shade = _shade_band if mode == "band" else _shade_slash
    for y in range(n):
        # 画布 y 向下, 场地 y 向下(与 ARENA 同口径) ⇒ 不翻转
        fy = (y + 0.5) / n * 2.0 * VIEW - VIEW + oy
        qy = y // SS
        for x in range(n):
            fx = (x + 0.5) / n * 2.0 * VIEW - VIEW + ox
            r = math.hypot(fx, fy)
            ## ★严格卡在判定带内: **画出来的范围必须 == 打得到的范围**。
            ##   第一版留了 ±1.5% 余量, 实测画到 r=1.0172(超出外边界 14 码) ——
            ##   站在 805 码的敌人身上画了光却不掉血, 就是通病「演出与判定不一致」。
            if r < R_IN or r > R_OUT:
                continue
            a = math.atan2(fy, fx) - d_ang
            while a > math.pi:
                a -= 2.0 * math.pi
            while a < -math.pi:
                a += 2.0 * math.pi
            if abs(a) > half:
                continue
            col = shade(r, a, half, t, (x // SS, qy))
            if col is not None:
                ld[x, y] = col + (255,)
    return img


## ─────────────────────────────────────────────────────────────
## 图标 —— 32×32 弯刀(旧图标是一把直剑, 名实不符)
## ─────────────────────────────────────────────────────────────
def render_icon(px):
    """32x32 弯刀图标。旧图标是一把**直剑**(64x64/43 色/2 半透), 名实不符。

    ★这一版是照着第一版逐像素打表改的 —— 第一版三个真毛病, 都是"不逐像素看就发现不了"的:
      ① **第 23/24 行整行空白**: 刀身与护手断开两格, 上屏读成一片指甲而不是刀。
         病根是刀身只从贝塞尔 s>0.16 开始画, 而护手在 v=0.80 —— 中间那截谁也没画。
      ② **不收尖**: 宽度公式虽然在缩, 但尖端外侧的像素按"到端点的距离"算, 于是留下一个
         半径 = 当地宽度的**圆帽**。要显式让 w(s=1) → 0。
      ③ **刃口在凹侧**: 弯刀的开刃面在**凸侧**(外弧), 我把亮边放到了凹侧, 正好反了。
    ★32x32 上不许"加细节": 尺寸小到这个程度, 细节只会变噪点, 性格必须靠**轮廓**给
      (memory: 尺寸小到某个程度加细节只会变噪点)。所以只保留四段轮廓: 刃 / 护手 / 柄 / 柄头。
    """
    n = px * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    ld = img.load()
    ## 刀脊曲线: 从护手正上方起, 弯向右上角。p0 的 v 与护手顶边对齐 ⇒ 不会再断开。
    P0 = (0.285, 0.780)
    P1 = (0.340, 0.330)
    P2 = (0.845, 0.140)

    def bez(s):
        m = 1.0 - s
        return (m * m * P0[0] + 2 * m * s * P1[0] + s * s * P2[0],
                m * m * P0[1] + 2 * m * s * P1[1] + s * s * P2[1])

    def tang(s):
        return (2.0 * (1.0 - s) * (P1[0] - P0[0]) + 2.0 * s * (P2[0] - P1[0]),
                2.0 * (1.0 - s) * (P1[1] - P0[1]) + 2.0 * s * (P2[1] - P1[1]))

    NS = 400
    pts = [(bez(i / float(NS - 1)), i / float(NS - 1)) for i in range(NS)]
    for y in range(n):
        v = (y + 0.5) / n
        for x in range(n):
            u = (x + 0.5) / n
            best = 9.0
            bs = 0.0
            for (pt, s) in pts:
                dd = (u - pt[0]) ** 2 + (v - pt[1]) ** 2
                if dd < best:
                    best = dd
                    bs = s
            dist = math.sqrt(best)
            ## ★宽度必须在 s=1 处真的归零, 否则尖端是个圆帽
            w = 0.082 * (1.0 - bs) ** 0.80
            if w > 0.002 and dist < w:
                cxp, cyp = bez(bs)
                tx, ty = tang(bs)
                ## 叉积定侧: >0 与 <0 分别是曲线的两侧。弯刀的**开刃面在凸侧**(外弧)。
                side = tx * (v - cyp) - ty * (u - cxp)
                e = dist / w                       # 0=刀脊中线 1=轮廓
                if e > 0.82:
                    ld[x, y] = P[5] + (255,)       # 硬描边(两侧都有, 像素画的规矩)
                elif side > 0.0:
                    ## 凸侧 = 开刃面: 越靠外越亮, 最外一档是磨亮的刃缘
                    ld[x, y] = (P[0] if e > 0.52 else P[1]) + (255,)
                else:
                    ## 凹侧 = 刀背: 越靠外越暗
                    ld[x, y] = (P[4] if e > 0.52 else P[3]) + (255,)
                continue
            ## 护手: 窄且**正压在刀身根部**(u 以 P0 为中心), 两端各一格描边
            if 0.780 <= v < 0.840 and abs(u - P0[0]) < 0.145:
                ld[x, y] = (P[5] if (v >= 0.822 or abs(u - P0[0]) > 0.118) else P[2]) + (255,)
                continue
            ## 刀柄: 3 像素宽, 与护手相连
            if 0.840 <= v < 0.930 and abs(u - P0[0]) < 0.050:
                ld[x, y] = (P[5] if abs(u - P0[0]) > 0.032 else P[3]) + (255,)
                continue
            ## 柄头: 比柄宽一圈的实心块 ⇒ 轮廓上有个"结", 才读得出是握把不是棍
            if 0.930 <= v < 0.995 and abs(u - P0[0]) < 0.072:
                ld[x, y] = (P[5] if (v >= 0.975 or abs(u - P0[0]) > 0.052) else P[2]) + (255,)
    return img


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True, help="大图输出目录(d{i}_f{j}.png)")
    ap.add_argument("--mode", choices=["band", "slash", "icon"], required=True)
    ap.add_argument("--dirs", type=int, default=16)
    ap.add_argument("--frames", type=int, default=1)
    ap.add_argument("--px", type=int, default=192, help="**最终**格边长; 实际渲 px*SS 再交给 pixelize_sheet")
    a = ap.parse_args()

    os.makedirs(a.out, exist_ok=True)
    n = 0
    if a.mode == "icon":
        render_icon(a.px).save(os.path.join(a.out, "d0_f0.png"))
        n = 1
        print("  icon: 渲了 1 张大图 (%dpx)" % (a.px * SS))
    else:
        for d in range(a.dirs):
            d_ang = math.tau * d / float(a.dirs)
            for f in range(a.frames):
                render_cell(a.mode, d_ang, f, a.frames, a.px).save(
                    os.path.join(a.out, "d%d_f%d.png" % (d, f)))
                n += 1
        print("  %s: 渲了 %d 张大图 (%d 向 x %d 帧, 每张 %dpx)"
              % (a.mode, n, a.dirs, a.frames, a.px * SS))
    if n == 0:
        print("[FAIL] 一张都没渲 —— 空目录不是通过")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())

## Bayer 4x4 有序抖动矩阵(阈值 0..15)。★用它而不是哈希噪点:
## 哈希读成噪点/磨砂, 有序抖动读成网点/半调 —— 后者是像素画里表达"半透明"的标准手法。
BAYER4 = [
    [0, 8, 2, 10],
    [12, 4, 14, 6],
    [3, 11, 1, 9],
    [15, 7, 13, 5],
]


def _frac(x):
    """确定性伪随机 0..1 —— 同一个 x 永远给同一个值(可复现, 不用 random)。"""
    v = math.sin(x * 12.9898) * 43758.5453
    return v - math.floor(v)


def _wobble(a, seed, amp, freq):
    """沿角度 a 的低频抖动: 让弧不是数学上完美的圆弧(完美 = 读成程序生成)。"""
    return amp * (math.sin(a * freq + seed) * 0.6 + math.sin(a * freq * 2.7 + seed * 1.7) * 0.4)


## ─────────────────────────────────────────────────────────────
## 预警区 band —— 一片**填充**的环形扇区, 不是几条线
## ─────────────────────────────────────────────────────────────
def _shade_band(r, a, half, t, pxq):
    """pxq = (最终像素 x, 最终像素 y), 抖动只能用它。

    ★★这一版是照着【和旧版并排量】改的(2026-09-09):
      第一版我拿"底色 + 矩形短划"填满整条带, 上屏读成**铺了砖的板**。
      并排量才看清差别在哪 ——
        旧版(用户认可的那版): 区域内 **148 种颜色的平滑渐变**, 中位亮度 89 ⇒ 读作**地上的一片光**
        我第一版:            **4 档硬边、70% 是同一个平色** + 矩形短划 ⇒ 读作**板**
      (顺带纠正我自己的目测: 我以为新版"太亮太实", 实测中位亮度 58 < 旧版 89, 是**更暗**的。)
    ★像素画不能用平滑渐变, 但有等价手段: **Bayer 有序抖动**做的渐变。
      覆盖率从带心往两端递减, 稀的地方**直接透出地面** —— 这才是"光", 不是"漆"。
      用 Bayer 而不是哈希噪点: 哈希读成**噪点/磨砂**, 有序抖动读成**网点/半调**, 是印刷与像素画里
      表达"半透明"的标准手法。
    ★仍然保留三样**信息量**(预兆必须自带信息, 不能只是好看):
      · 内外两条边界弧(实心) = 判定带的两个边在哪
      · 带心一条更亮的线(实心) = 斩痕待会儿落在哪
      · 角向两端**不封口**(靠覆盖率归零自然消散) —— 闭合的亮轮廓永远读作物体
    """
    qx, qy = pxq
    ua = abs(a) / half
    th = float(BAYER4[qy & 3][qx & 3]) / 16.0
    ## ★两端一起化开: 最后 15% 的角度里, 连边界弧与带心线也改成抖动收尾。
    ##   否则填充化开了、两条弧却还是被**直切一刀**, 端头依旧读成"被剪断的板"。
    tip = 1.0 if ua < 0.85 else (1.0 - ua) / 0.15
    ## ① 内外边界: 各一条亮弧, 只画在带内侧(不越界 ⇒ 画出来的范围 == 打得到的范围)
    if r - R_IN < 0.011 or R_OUT - r < 0.011:
        return P[3] if tip > th else None
    ## ★★这里**曾经**有一条"带心更亮的线", 已删(用户 2026-09-09):
    ##   「更亮的线根本比预警区小太多啊, 预警是告诉玩家要实际产生伤害的地区啊」
    ##   —— 伤害打的是整条 304 码宽的带, 不是一条线。在预警里画一条亮线等于宣称
    ##   "打这儿", 是**错的信息**。预警区的唯一职责就是标出【这一整片会挨伤害】,
    ##   边界由内外两条弧说清, 里面**不许有任何东西宣称一个更小的范围**。
    ## ③ 抖动渐变填充。覆盖率 cov:
    ##    角向 —— 从带心 1.0 递减到两端 0(所以两端是"化开"的, 不是被直切一刀)
    ##    径向 —— 中间略高、贴近两条边界略低(边界由 ① 负责说清, 这里不跟它抢)
    ur = (r - R_MID) / (0.5 * (R_OUT - R_IN))
    cov = (1.0 - ua ** 2.6) * (1.0 - 0.30 * ur * ur)
    cov = max(0.0, cov) * 1.35                      # 1.35: 让带心附近能到第二档
    if cov > 1.0 + th:
        return P[3]
    if cov > th:
        return P[4]
    return None


## ─────────────────────────────────────────────────────────────
## 斩痕 slash —— 沿带心的一条波形亮带, 叠在 band 上面
## ─────────────────────────────────────────────────────────────
def _shade_slash(r, a, half, t, pxq):
    """斩痕 = **一刀从扇形的一端扫到另一端**, 扫过之处盖满整条判定带。

    ★★这一版是被用户 2026-09-09 的三句话逼出来的, 每一句对应一个真缺陷:
      ①「更亮的线你这没有从一边到另一边的感觉啊」
         —— 上一版**每一帧都跨满 60 度**(实测 f0~f3 全是 -30.1~30.0), 是原地张开不是扫。
            弯刀就该是扫过去的, 一刀从一端扫到另一端。
      ②「更亮的线根本比预警区小太多啊, 预警是告诉玩家要实际产生伤害的地区啊」
         —— 上一版斩痕最宽 166 码, 而判定带宽 **304 码**, 只盖住 55%。
            玩家看见细细一道白光却整片掉血 = 通病「画出来的和打到的不是一回事」。
            ⇒ 扫过的每一处都必须**盖满 R_IN..R_OUT 的全宽**。
      ③「斩击后为什么还有预警？」—— 那条在代码侧改(预警一起手就退场), 不在这里。

    ★为什么盖满整条带**不会**读成"实心半月盘"(上一版就是怕这个才改窄的, 结果引入了更大的错):
      盘之所以读成盘, 是因为它**同时**满、且各处一样亮。扫过去的刀不是:
        · 只有**领先边**是烫白的一条(那是刀刃), 后面按距离衰减成拖尾;
        · 领先边之前的角度**什么都没有**(还没扫到);
        · 拖尾末端用抖动化开, 不是硬切。
      ⇒ 任何一帧看到的都是"一把刀 + 它划过的痕", 不是一块板。

    ★时序: 前 55% 的帧进度把刀从 -half 扫到 +half(约 0.33 秒 = 一次挥砍),
      后 45% 整片痕碎开消散。伤害在第 0 帧就结完(斩击本来就是瞬间的)。
    """
    qx, qy = pxq
    ## 领先边(刀刃当前所在的角度): 从 -half 扫到 +half。
    ## ★起点要给 0.10 的预偏移: 直接从 t=0 起扫的话, 第 0 帧刀刃正好落在起点、
    ##   一点面积都没有 —— 实测 f0 全空, 5 帧白费 1 帧。
    sweep = min(1.0, (0.10 + t) / 0.60)
    lead = -half + 2.0 * half * sweep
    if a > lead:
        return None                                  # 还没扫到这里
    ## 距离领先边多远(0=刀刃上, 1=扇形另一端)
    d = (lead - a) / (2.0 * half)
    ## ── 径向: **盖满整条判定带**, 只用亮度分层, 不留空 ──
    ur = (r - R_IN) / (R_OUT - R_IN)                 # 0=内边界 1=外边界
    rad = 1.0 - 0.42 * (2.0 * ur - 1.0) ** 2         # 中间亮、两边略暗, 但都不为 0
    ## ── 角向: 领先边最亮, 往后**衰减到没有** ──
    ## ★★这里第一版写成 `rad * (0.30 + 0.70 * trail)` —— 留了个 0.30 的**地板**,
    ##   于是拖尾再远也不低于 P[2]/P[3], 整个扫过的扇区全是亮的 ⇒ **实拍就是一块实心板**
    ##   (正是我改窄斩痕时想避免的那个读法, 绕一圈又踩回来了)。
    ##   真刀的拖痕是会消失的: 任何一帧看到的应该是「刀 + 一小段拖痕」,
    ##   而"整片都被切过"是**五帧累计**的结果 —— 并集判据本来就是按累计写的, 不需要单帧全满。
    trail = (1.0 - d) ** 2.2
    v = rad * trail
    ## 刀刃本身: 领先边前 4% 的一条, 压成最亮 —— 这是"一把刀"的读法所在
    blade = d < 0.040
    ## ── 碎开: 后 45% 按【角度 x 径向】二维格子开洞 ──
    if t > 0.55:
        k = (t - 0.55) / 0.45
        ## ★格子的长宽比要算, 不能拍脑袋: 角向 N_a 份在 r=R_MID 处每格弧长 = R_MID*(2*half)/N_a,
        ##   径向 N_r 份每格 = (R_OUT-R_IN)/N_r。要方 ⇒ N_r ≈ 0.44*N_a。
        ##   第一版 (19, 4) 算出来是 36 码 x 75 码 —— 格子被拉成 2 倍高的长条,
        ##   实拍碎成**横向条纹**, 读成百叶窗不是碎裂(这条上一代代码里就警告过, 我又踩了一次)。
        ##   (16, 7) ⇒ 42 码 x 43 码, 方的。
        ca = math.floor(a * 15.3 + _frac(math.floor(ur * 7.0) * 5.3) * 2.0)
        cu = math.floor(ur * 7.0)
        if _frac(ca * 1.0 + cu * 7.31) < k * 0.86:
            return None
        if _frac(ca * 2.7 + cu * 3.19) < k * 0.32:
            return None
    th = float(BAYER4[qy & 3][qx & 3]) / 16.0
    if blade:
        return P[0]                                  # 刀刃本身: 一条硬亮边, 不参与抖动
    ## ★★色阶用**有序抖动量化**, 不用固定阈值阶梯。
    ##   固定阈值那版实拍是一圈圈清晰的同心色带 ⇒ 读成**等高线/地形图**而不是刀的拖痕
    ##   (这条我在上一代代码里专门注释警告过"完全等距的同心色带会读成等高线", 新公式里漏掉了)。
    ##   把 Bayer 阈值加进量化本身, 相邻色阶之间就变成半调过渡, 没有硬边界;
    ##   同时最暗那档自然地稀疏到透明 ⇒ 拖痕真的会"用完", 不是被一刀切掉。
    lv = v * 5.2 + th
    bi = int(math.floor(lv))
    if bi <= 0:
        return None
    return P[max(0, 5 - bi)]


def render_cell(mode, d_ang, f, nframes, px):
    """渲一格(某方向某帧)的大图, 返回 RGBA Image。"""
    n = px * SS
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    ld = img.load()
    half = math.radians(HALF_DEG)
    t = f / float(max(1, nframes - 1))          # 0..1 帧进度
    ox = R_MID * math.cos(d_ang)                # 画布中心 = 释放点 + 瞄准方向 × 带心半径
    oy = R_MID * math.sin(d_ang)
    shade = _shade_band if mode == "band" else _shade_slash
    for y in range(n):
        # 画布 y 向下, 场地 y 向下(与 ARENA 同口径) ⇒ 不翻转
        fy = (y + 0.5) / n * 2.0 * VIEW - VIEW + oy
        qy = y // SS
        for x in range(n):
            fx = (x + 0.5) / n * 2.0 * VIEW - VIEW + ox
            r = math.hypot(fx, fy)
            ## ★严格卡在判定带内: **画出来的范围必须 == 打得到的范围**。
            ##   第一版留了 ±1.5% 余量, 实测画到 r=1.0172(超出外边界 14 码) ——
            ##   站在 805 码的敌人身上画了光却不掉血, 就是通病「演出与判定不一致」。
            if r < R_IN or r > R_OUT:
                continue
            a = math.atan2(fy, fx) - d_ang
            while a > math.pi:
                a -= 2.0 * math.pi
            while a < -math.pi:
                a += 2.0 * math.pi
            if abs(a) > half:
                continue
            col = shade(r, a, half, t, (x // SS, qy))
            if col is not None:
                ld[x, y] = col + (255,)
    return img



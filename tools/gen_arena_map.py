def sup(dx, dy, p):
    a, b, n = p
    return ((abs(dx) / a) ** n + (abs(dy) / b) ** n) ** (1.0 / n)


def wobble(th, a1, f1, p1, a2, f2, p2):
    """按极角给分界半径加两层正弦扰动 —— 完美椭圆看着像 CAD 不像海底。
    ★★网格加密后振幅要【调小】不是调大 —— 我一开始想反了: 振幅是半径的比例, 物理起伏没变,
      但量化台阶只有原来一半 ⇒ 同样的起伏【看得更清楚】。加密后照搬旧振幅, 海岸线会从
      "有机"变成"撕破的纸边"(实测)。
    ★振幅上限 0.035: v1 用了 0.055, 换算到上下方向 = 0.055*548 ≈ 30px, 不到半格,
      但叠在网格量化上就变成"1格进1格出"的毛边。低频(2~3)大幅、高频只留一丝。
    ★用确定性正弦而不是 random: 生成器要能重跑出同一张图。"""
    return 1.0 + a1 * math.sin(f1 * th + p1) + a2 * math.sin(f2 * th + p2)


## ★★★2026-10-03「战斗区只用一种地面材质」。
##
## 【为什么】逐张看咩咩的参考(raw_01 地牢 / raw_18 BOSS 场 / raw_04 营地)才看出来的一条:
##   **它们的战斗区地面基本是单一材质**, 变化来自柔和的明暗斑块; 地标是**物件**, 不是地面涂色。
##   我们在 26 格宽的岛上塞了草/沙/石三种材质, 而一格 = 38.4px ⇒ 类型边界必然是硬台阶,
##   整片地读成"拼出来的棋盘"。实拍对比: 去掉之后那层棋盘感当场消失。

##   ⇒ 在物件补回来之前, 场地结构的可读性是**暂时降低**的, 这一点显式记在这里。
##
## ★两座**基地石台**保留 —— 它们标的是"哪边是我方", 是真·玩法信息, 而且只有两块、不碎地面。
_EXP_SINGLE_FLOOR = True


def classify(dx, dy):
    th = math.atan2(dy, dx)

    # ── ① 岛外: 先判海, 再判 void ──────────────────────────────────────
    #   ★岸线扰动幅度压到 1.2% —— 必须小于半格(TILE/2=19.2px)才不会把"明确在可活动区内"
    #     的格子吃成水。实测 1.2% × 364 = 4.4px / × 798 = 9.6px, 都远小于半格。
    #     (判据 verify_island_boundary 对边界那一圈格子不下断言, 但别靠它兜底。)
    isle_t = sup(dx, dy, ISLE) / wobble(th, 0.012, 2.0, 1.5, 0.006, 3.0, 0.2)
    if isle_t > 1.0:
        return WATER if sup(dx, dy, SEA) <= 1.0 else VOID

    # ── ② 岛内: 基地石台(站位列整段吃满) ─────────────────────────────
    #   ★★顺序即语义: 这段必须在"水"之后、岛内地标之前。改前它被放在水之前, 原因是
    #     梭形岛会让站位列最外那格落到岛外; 现在岛 = 可活动区, 站位列必然在岛上,
    #     但保留这个顺序不会错, 而且万一以后 ARENA_SHAPE_N 调成更圆的还能兜住。
    for _sgn in (-1.0, 1.0):
        # ★同 ④: 石台边界也吃扰动, 否则两块规整的圆角方摆在那里很"CAD"。
        #   角度要按**它自己的中心**算, 不是岛心 —— 按岛心算的话石台的扰动会沿岛心方向拉扯变形。
        _bth = math.atan2(dy, dx - _sgn * BASE_DX)
        if sup(dx - _sgn * BASE_DX, dy, BASE) < wobble(_bth, 0.070, 2.0, 1.1, 0.035, 4.0, 0.3):
            return STONE

    # ── ③ 岸线: 贴着海的内缘留一圈石, 给岛一条【明确的轮廓】 ──────────
    #   暗地面直接接亮水时, 岛只是"亮的地方之外剩下的形状", 自己没有边;
    #   插一档中间值(石)在中间, 岛就成了一个有边的实体。
    #   ★29×17 时试过并否掉: 1 格宽的曲线边被量化成断续的点。58×34 下有 2 格, 边连得起来。
    if isle_t > SHORE_FRAC:
        return STONE

    # ── ④ 岛心内部: 只留 3 个大地标, 其余是地面(单位立绘最好读) ──────
    #
    # ★★★2026-10-03 内部地标的边界【吃上扰动】。
    #   由来: 实拍之后地面读成「38.4px 的方格棋盘」, 而咩咩的地面是**有机涂抹色块**
    #   (逐张看了 raw_01/raw_13/raw_04/raw_18 才看出来的 —— 上一轮那份统计报告量不出这一维)。
    #   根因不在 shader(它已经有 sediment 噪声 + 抖动分级 + 距离场湿带), 而在**这里**:
    #   `CORE` 是正椭圆、`SPINE` 是正矩形 ⇒ 量化到一格就是阶梯边, 一眼就是"拼出来的"。
    #   岛的外轮廓本来就有 `wobble()`, 内部地标却一直是裸几何 —— 补上同一条。
    # ★振幅比外轮廓大: 外轮廓必须小于半格(否则会啃掉可活动区的格子, 见 ① 的注释),
    #   而内部地标怎么扭都还在岛上, 不影响玩法 ⇒ 可以给到看得见的程度。
    if _EXP_SINGLE_FLOOR:
        pass
    elif sup(dx, dy, CORE) < wobble(th, 0.085, 3.0, 0.7, 0.040, 5.0, 2.1):
        return SAND                              # 场心 = 争夺点
    # ★中轴石道原来是**正矩形** `abs(dy) <= SPINE_DY` ⇒ 画面上一条笔直的横带, 最像"贴上去的"。
    #   改成沿 x 起伏的带: 用 dx 当相位, 两层正弦, 幅度 ±22%。
    spine_w = SPINE_DY * (1.0 + 0.22 * math.sin(dx * 0.016 + 0.6)
                          + 0.10 * math.sin(dx * 0.037 + 2.4))
    if (not _EXP_SINGLE_FLOOR) and abs(dy) <= spine_w and abs(dx) <= BASE_DX:
        return STONE                             # 中轴石道: 把两座石台与场心串成一条横轴
    return GRASS


def build():
    return [[classify(OX + (c + 0.5) * TILE - CX, OY + (r + 0.5) * TILE - CY)
             for c in range(W)] for r in range(H)]


def report(grid):
    ch = ['.', '~', '#', ':', ' ']
    n = W * H
    cnt = [sum(row.count(k) for row in grid) for k in range(5)]
    nm = ['淤泥', '水', '石', '沙', 'void']
    print("分布: " + "  ".join("%s %d(%.0f%%)" % (nm[k], cnt[k], 100.0 * cnt[k] / n) for k in range(5)))
    bad_v = [1 for r in range(H) for c in range(W) if grid[r][c] == VOID
             and abs(OX + (c + .5) * TILE - CX) <= PLAY_DX and abs(OY + (r + .5) * TILE - CY) <= PLAY_DY]
    bad_w = [1 for r in range(H) for c in range(W) if grid[r][c] == WATER
             and abs(OX + (c + .5) * TILE - CX) <= CLASH_DX and abs(OY + (r + .5) * TILE - CY) <= CLASH_DY]
    print("硬约束: 战场内 void %d(要0) / 接战区内水 %d(要0) / void占比 %.0f%%(门禁要 5~60%%)"
          % (len(bad_v), len(bad_w), 100.0 * cnt[VOID] / n))
    print("列号: " + "".join(str(c % 10) for c in range(W)))
    for r in range(H):
        tag = '  ← 战场上/下沿' if r in (3, 12) else ('  ← 屏外(永远看不见)' if r >= 15 else '')
        print("%2d |%s|%s" % (r, "".join(ch[v] for v in grid[r]), tag))
    print("    " + "".join('^' if 5 <= c <= 22 else ' ' for c in range(W)) + "  (^=不被队伍面板遮的列)")
    print("    " + "".join('B' if c in (8, 9, 19, 20) else ' ' for c in range(W)) + "  (B=两队站位列)")
    return not bad_v and not bad_w and 0.05 < cnt[VOID] / n < 0.60


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='data/maps/arena.json')
    a = ap.parse_args()
    grid = build()
    ok = report(grid)
    # ★逐行拼再一次写出 —— 不用 json.dump(默认无缩进, 会把 493 格压成一整行, diff 没法看;
    #   也不用 indent=2, 那样每个格子占一行 = 900 多行)。每行地图 = 文件里的一行, 正好能读。
    nl = chr(10)
    out = ['{']
    out.append('  "tile": %r,' % TILE)
    out.append('  "origin_x": %r,' % OX)
    out.append('  "origin_y": %r,' % OY)
    out.append('  "w": %d,' % W)
    out.append('  "h": %d,' % H)
    out.append('  "types": ["grass", "water", "stone", "sand", "void"],')
    out.append('  "grid": [')
    out.append((',' + nl).join('    ' + json.dumps(row) for row in grid))
    out.append('  ],')
    out.append('  "height": [')
    out.append((',' + nl).join('    ' + json.dumps([0.0] * W) for _ in range(H)))
    out.append('  ]')
    out.append('}')
    with io.open(a.out, 'w', encoding='utf-8', newline=nl) as f:
        f.write(nl.join(out) + nl)
    json.load(io.open(a.out, encoding='utf-8'))          # ★写盘后立刻回读一次, 确认不是坏 json
    print(nl + "写出 %s   %s" % (a.out, "✓ 硬约束通过" if ok else "✗ 硬约束没过"))


if __name__ == '__main__':
    main()

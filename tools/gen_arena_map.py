## ⚠ 这**去掉了 2026-07-31 刻意设计的两个地面地标**(场心沙=争夺点 / 中轴石道=串起两座石台),
##   不是顺手删的:
##   · 它们的作用是"让玩家读出场地结构", 而参考用**物件**做这件事, 效果更好且不碎地面;

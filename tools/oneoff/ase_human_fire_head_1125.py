    u.color("c42a1a"); _c([(68, 18), (65, 13), (59, 12), (52, 12), (44, 13), (36, 12), (30, 14), (22, 17), (r, 18), (22, 19), (30, 21), (38, 23), (46, 23), (53, 24), (60, 24), (65, 22), (68, 18)])

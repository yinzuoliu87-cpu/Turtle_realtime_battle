    u.move(3000, 1450); u.key("d"); time.sleep(0.2)
    u.color("5e1450"); _c([(70, 18), (68, 11), (62, 7), (50, 6), (38, 9), (26, 12), (14, 15), (ht, 18), (14, 21), (26, 24), (38, 27), (50, 30), (62, 29), (68, 25), (70, 18)])
